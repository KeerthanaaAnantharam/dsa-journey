package Beginner.InputOutput;
//Given two numbers A and B. Concatenate the two numbers and print it.

import java.lang.*;
import java.util.*;

public class ConcatenateNumbers{
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        int A = sc.nextInt();
        int B = sc.nextInt();
        System.out.print(A);
        System.out.print(B);
    }
}